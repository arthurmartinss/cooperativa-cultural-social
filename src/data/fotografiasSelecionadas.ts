export function urlOtimizada(foto: FotografiaSelecionada, largura: number) {
  const url = new URL(foto.rawUrl)
  url.searchParams.set('w', String(Math.min(largura, foto.largura)))
  url.searchParams.set('q', '82')
  url.searchParams.set('auto', 'format')
  url.searchParams.set('fit', 'crop')
  url.searchParams.set('crop', 'entropy')
  return url.toString()
}

export function srcSetResponsivo(foto: FotografiaSelecionada) {
  return [480, 768, 1080, 1440, 1920]
    .filter((largura) => largura <= foto.largura)
    .map((largura) => `${urlOtimizada(foto, largura)} ${largura}w`)
    .join(', ')
}
